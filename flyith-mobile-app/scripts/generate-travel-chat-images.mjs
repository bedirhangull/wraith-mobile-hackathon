#!/usr/bin/env node
/**
 * Walks assets/assets-for-travel-chat and emits a Metro-friendly require() map
 * keyed by normalized city/country folder names.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const ASSETS = path.join(ROOT, "assets", "assets-for-travel-chat");
const OUT = path.join(
  ROOT,
  "src",
  "features",
  "travel-chat",
  "assets",
  "localTripImages.generated.ts"
);

const SKIP_DIR_RE = /backgorund|background|vheer|ds_store/i;

function normalizeKey(name) {
  return name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/ı/g, "i")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, "-");
}

/** @type {Record<string, string[]>} */
const map = {};

/**
 * @param {string} dir
 * @param {string | null} countryKey
 * @param {string | null} cityKey
 */
function walk(dir, countryKey, cityKey) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    if (SKIP_DIR_RE.test(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!countryKey) {
        walk(full, normalizeKey(entry.name), null);
      } else if (!cityKey) {
        walk(full, countryKey, normalizeKey(entry.name));
      } else {
        walk(full, countryKey, cityKey);
      }
      continue;
    }
    if (!/\.png$/i.test(entry.name)) continue;
    const relFromApp = path.relative(path.dirname(OUT), full).split(path.sep).join("/");
    const requirePath = relFromApp.startsWith(".") ? relFromApp : `./${relFromApp}`;

    if (cityKey) {
      if (!map[cityKey]) map[cityKey] = [];
      if (!map[cityKey].includes(requirePath)) map[cityKey].push(requirePath);
    }
    if (countryKey) {
      if (!map[countryKey]) map[countryKey] = [];
      if (!map[countryKey].includes(requirePath) && map[countryKey].length < 24) {
        map[countryKey].push(requirePath);
      }
    }
  }
}

walk(ASSETS, null, null);

const keys = Object.keys(map).sort();
const lines = [
  "/* AUTO-GENERATED by scripts/generate-travel-chat-images.mjs — do not edit by hand. */",
  'import type { ImageSourcePropType } from "react-native";',
  "",
  "export const LOCAL_TRIP_IMAGES: Record<string, ImageSourcePropType[]> = {",
];

for (const key of keys) {
  const paths = map[key];
  if (!paths.length) continue;
  lines.push(`  "${key}": [`);
  for (const p of paths) {
    lines.push(`    require("${p}"),`);
  }
  lines.push("  ],");
}
lines.push("};");
lines.push("");

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join("\n"));
console.log(
  `Wrote ${OUT} with ${keys.length} keys, ${keys.reduce((n, k) => n + map[k].length, 0)} requires.`
);
